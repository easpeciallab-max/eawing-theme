/**
 * ค่าเริ่มต้นของช่องรูป 1 ช่อง (ไม่มีรูปในธีม · แอดมินอัปโหลดเองตาม _img_note)
 */
function eaw_guide_media_defaults( $key, $alt, $note ) {
	return array(
		$key . '_img'         => '',
		$key . '_img_mobile'  => '',
		$key . '_img_alt'     => (string) $alt,
		$key . '_img_caption' => '',
		$key . '_img_note'    => '' !== (string) $note ? 'ภาพที่ต้องใส่: ' . $note : '',
	);
}

